def test_a_declined_prompt_is_explained_and_the_next_click_asks_again(env):
    capabilities, tab, api, temp, _ = env
    sliced(capabilities, temp)
    slice_id = tab.slices()[0]["id"]
    _audit.answer = lambda category, target: False

    reply = tab.click_log(slice_id)

    assert reply["event"] == {
        "kind": "failed",
        "id": slice_id,
        "message": (
            "Orca blocked the upload because permission was declined. "
            "Click Log again to be asked again."
        ),
        "declined": True,
    }
    (item,) = reply["slices"]
    assert (item["status"], item["error"]) == ("not logged", True)
    assert ui.windows == []
    assert api == []

    _audit.answer = None
    assert tab.click_log(slice_id)["event"]["kind"] == "logged"
    assert [yes for *_, yes in _audit.prompts] == [False, True]


