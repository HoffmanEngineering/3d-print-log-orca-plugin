def test_the_tab_logs_the_hooks_exact_exported_file(env, tmp_path):
    capabilities, tab, api, temp, _ = env
    sliced(capabilities, temp)
    working = temp / ".1234.0.gcode.pp"
    working.write_text("; generated by OrcaSlicer 2.5.0-alpha on x\n; post-processed\n")
    ctx = orca.slicing.SlicingPipelineContext(
        gcode_path=str(working), host="File", output_name=str(tmp_path / "Benchy_PLA.gcode")
    )
    orca_driver.execute(capabilities["3D Print Log uploader"], ctx)
    working.unlink()  # Orca removes its working copy after the hook

    reply = tab.click_log(tab.slices()[0]["id"])

    assert reply["event"]["kind"] == "logged"
    assert '"outputName": "Benchy_PLA.gcode"' in api[0]
    assert _audit.prompts == []  # the copy is in plugin storage: nothing to ask
