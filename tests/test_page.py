"""The 3D Print Log tab through the fake Orca: the messages its script sends, on the UI thread,
inside the plugin's audit context."""

import json
import logging
import re
from urllib.parse import parse_qs, urlsplit

import orca
import orca_driver
import pytest
from orca import _audit

from printlog_orca import controller, page, uploader
from printlog_orca.client import UploadResult

TAB = "3D Print Log"
SCRIPT = "Log last slice to 3D Print Log"
SETTING_ID = "6f9619ff-8b86-d011-b42d-00c04fc964ff"
Event = orca.LifecycleEvent


class FakeApi(list):
    def __init__(self):
        super().__init__()
        self.result = UploadResult(True, 200, "uploaded", SETTING_ID)

    def __call__(self, api_base, body, content_type, timeout=30):
        self.append(body.decode("utf-8", errors="replace"))
        return self.result


class Tab:
    """Plays the tab's script (page_html.py) against the plugin."""

    def __init__(self, capability):
        self.page = orca_driver.Page(capability)
        self.token = re.search(r'var TOKEN = "([0-9a-f]{32})"', self.page.html).group(1)
        self.location = None  # where the tab navigated itself
        self.seen = []  # every state the page rendered
        self.ready()

    def send(self, kind, **extra):
        replies = self.page.send({"type": kind, "token": self.token, **extra})
        self.seen.extend(replies)
        (reply,) = replies
        assert reply["type"] == "state"
        return reply

    def ready(self):
        return self.send("ready")

    def slices(self):
        return self.send("refresh")["slices"]

    def click_log(self, slice_id, relog=False):
        """Log (or Log again): the first reply paints Uploading…, then the page sends upload."""
        reply = self.send("log", id=slice_id, relog=relog)
        if reply["event"]["kind"] != "uploading":
            return reply
        self.painted = [s for s in reply["slices"] if s["id"] == slice_id][0]
        reply = self.send("upload", id=slice_id)
        event = reply["event"]
        if event["kind"] == "logged" and event["mode"] == "tab":
            self.location = event["url"]
        return reply


@pytest.fixture
def env(tmp_path, monkeypatch, plugin_log):
    storage = tmp_path / "OrcaSlicer" / "orca_plugins" / "plugin_data" / "printlog"
    storage.mkdir(parents=True)
    orca_driver.reset(storage)
    api = FakeApi()
    ctl = controller.Controller(upload=api)
    monkeypatch.setattr(controller, "shared", ctl)
    capabilities = orca_driver.load()
    orca_driver.on_load(capabilities)
    temp = tmp_path / "Temp" / "orcaslicer_model" / "Metadata"
    temp.mkdir(parents=True)
    tab = Tab(capabilities[TAB])
    yield capabilities, tab, api, temp, storage
    errors = [r for r in plugin_log if r.levelno >= logging.ERROR]
    assert errors == [], [r.getMessage() for r in errors]
    # Every prompt came modally on the UI thread, right after a click.
    assert [p for p in _audit.prompts if p[2] != "ui"] == []


def sliced(capabilities, temp, model="Benchy", name=".1234.0.gcode"):
    path = temp / name
    path.write_text("; generated by OrcaSlicer 2.5.0-alpha on x\nG28\n")
    orca_driver.fire(
        capabilities,
        Event.GCodeExportFinished,
        orca.LifecycleEventContext(name=model, msg=str(path)),
    )
    orca_driver.fire(capabilities, Event.SlicingJobComplete, orca.LifecycleEventContext(name=model))
    return path


def install_id(storage):
    return json.loads((storage / "install.json").read_text(encoding="utf-8"))["installId"]


