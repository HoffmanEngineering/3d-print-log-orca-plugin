def test_the_install_id_survives_a_restart(env, monkeypatch):
    capabilities, tab, api, temp, storage = env
    sliced(capabilities, temp)
    tab.click_log(tab.slices()[0]["id"])
    first = install_id(storage)

    monkeypatch.setattr(controller, "shared", controller.Controller(upload=api))  # a new session
    sliced(capabilities, temp)
    tab.ready()
    tab.click_log(tab.slices()[0]["id"])

    assert install_id(storage) == first
    assert all(f'"installId": "{first}"' in body for body in api)


