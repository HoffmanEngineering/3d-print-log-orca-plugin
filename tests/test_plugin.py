"""The capabilities as Orca loads and calls them, through the fake orca module: on Orca's
threads, inside its audit context, with orca.host.ui allowed only on the UI thread."""

import json
import logging

import orca
import orca_driver
import pytest
from orca import _audit
from orca.host import ui

from printlog_orca import controller, staging
from printlog_orca.client import UploadResult

UPLOADER = "3D Print Log uploader"
SCRIPT = "Log last slice to 3D Print Log"
TAB = "3D Print Log"
SETTING_ID = "6f9619ff-8b86-d011-b42d-00c04fc964ff"
IDS = {
    "print_settings_id": "0.20mm Standard @MK4S",
    "filament_settings_id": '"Prusa Generic PLA"',
    "printer_settings_id": "Prusa MK4S",
}
Event = orca.LifecycleEvent


class FakeApi(list):
    result = UploadResult(True, 200, "uploaded", SETTING_ID)

    def __call__(self, api_base, body, content_type, timeout=30):
        self.append(body.decode("utf-8", errors="replace"))
        return self.result


@pytest.fixture
def env(tmp_path, monkeypatch, plugin_log):
    storage = tmp_path / "OrcaSlicer" / "orca_plugins" / "plugin_data" / "printlog"
    storage.mkdir(parents=True)
    orca_driver.reset(storage)
    api = FakeApi()
    ctl = controller.Controller(upload=api)
    monkeypatch.setattr(controller, "shared", ctl)
    capabilities = orca_driver.load()
    orca_driver.on_load(capabilities)
    temp = tmp_path / "temp"  # Orca's temp folder: outside data_dir
    temp.mkdir()
    yield capabilities, api, temp, ctl, storage
    # Nothing raised inside a callback, and nothing Orca would have refused off the UI thread.
    errors = [r for r in plugin_log if r.levelno >= logging.ERROR]
    assert errors == [], [r.getMessage() for r in errors]
    assert [p for p in _audit.prompts if p[2] != "ui"] == []


def sliced(capabilities, temp, model="Benchy", code=None, name=".1234.0.gcode"):
    path = temp / name
    path.write_text("; generated by OrcaSlicer 2.5.0 on x\nG28\n")
    msg = str(path) if code is None else f"{path}\nG-code export failed"
    ok = code or orca.LifecycleEvtCode.Ok
    orca_driver.fire(
        capabilities,
        Event.GCodeExportFinished,
        orca.LifecycleEventContext(name=model, msg=msg, code=ok),
    )
    orca_driver.fire(
        capabilities, Event.SlicingJobComplete, orca.LifecycleEventContext(name=model, code=ok)
    )
    return path


def listed(ctl):
    return [(s["name"], s["destination"], s["status"]) for s in ctl.state()["slices"]]


def post_process(capabilities, host, gcode_path, output_name, step=None):
    ctx = orca.slicing.SlicingPipelineContext(
        step=step or orca.slicing.Step.psGCodePostProcess,
        gcode_path=str(gcode_path),
        host=host,
        output_name=str(output_name),
        config=IDS,
    )
    return orca_driver.execute(capabilities[UPLOADER], ctx)


def test_the_package_registers_the_uploader_the_tab_and_the_script(env):
    capabilities, *_ = env

    assert set(capabilities) == {UPLOADER, TAB, SCRIPT}
    assert capabilities[TAB].get_type() == orca.PluginType.Pages
    assert capabilities[UPLOADER].get_type() == orca.PluginType.SlicingPipeline
    assert capabilities[SCRIPT].get_type() == orca.PluginType.Script


def test_import_starts_no_thread_and_does_no_io():
    # The audit guard fails the test on plugin I/O outside a callback; loading is the risk.
    _audit.strict = True
    orca_driver.load()


