def test_the_hook_keeps_a_copy_of_an_export_without_a_prompt(env, tmp_path):
    capabilities, api, temp, ctl, storage = env
    sliced(capabilities, temp)
    working = temp / ".1234.0.gcode.pp"
    working.write_text("; generated by OrcaSlicer 2.5.0 on x\n; post-processed\n")

    result = post_process(capabilities, "File", working, tmp_path / "Benchy_PLA_1h.gcode")

    assert result.status == orca.PluginResult.Success
    assert listed(ctl) == [("Benchy", "Exported to Benchy_PLA_1h.gcode", "not logged")]
    (copy,) = staging.exports_dir(storage).iterdir()
    assert "; post-processed" in copy.read_text()
    assert api == []
    assert _audit.prompts == []


def test_the_hook_skips_other_steps(env):
    capabilities, _, temp, _, _ = env

    result = post_process(
        capabilities, "File", temp / "a.gcode", "b.gcode", step=orca.slicing.Step.posSlice
    )

    assert result.status == orca.PluginResult.Skipped


def test_the_hook_never_fails_the_slice(env, monkeypatch):
    capabilities, _, temp, _, _ = env

    def broken(*args, **kwargs):
        raise OSError("disk full")

    monkeypatch.setattr(staging, "export_copy", broken)
    logger = logging.getLogger("printlog_orca")
    logger.disabled = True
    try:
        result = post_process(capabilities, "File", temp / "x.gcode", temp / "out.gcode")
    finally:
        logger.disabled = False

    assert result.status == orca.PluginResult.Success


def test_the_script_logs_the_last_slice_on_the_ui_thread(env):
    capabilities, api, temp, ctl, storage = env
    sliced(capabilities, temp)

    result = orca_driver.run_script(capabilities[SCRIPT])

    assert result.status == orca.PluginResult.Success
    assert "Open claim page" in result.message
    assert len(api) == 1
    install_id = json.loads((storage / "install.json").read_text())["installId"]
    assert f'"installId": "{install_id}"' in api[0]
    assert listed(ctl)[0][2] == "logged"
    # Reading the temp G-code asked, modally, on the UI thread.
    assert [(c, k) for c, _, k, _ in _audit.prompts] == [("file", "ui")]


