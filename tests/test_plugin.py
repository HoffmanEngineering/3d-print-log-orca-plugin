@pytest.mark.parametrize("event", [Event.PrintJobStarted, Event.SendJobStarted])
def test_a_bambu_send_marks_the_slice_and_notifies_on_the_next_ui_event(env, event):
    capabilities, api, temp, ctl, _ = env
    sliced(capabilities, temp)
    ui.reset()

    orca_driver.fire(
        capabilities, event, orca.LifecycleEventContext(name="Desk organizer", device_id="01P")
    )
    assert ui.notifications == []  # the job worker cannot show one
    orca_driver.fire(
        capabilities, Event.PrintStateChanged, orca.LifecycleEventContext(msg="PREPARE")
    )
    orca_driver.fire(
        capabilities, Event.PrintStateChanged, orca.LifecycleEventContext(msg="RUNNING")
    )

    assert listed(ctl) == [("Benchy", "Sent to Bambu", "not logged")]
    assert [n.text for n in ui.notifications] == [
        "Sent Benchy to the printer. Open the 3D Print Log tab to log it."
    ]
    assert api == []


