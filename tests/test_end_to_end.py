"""An export in Orca reaches a local API as one multipart POST, through the real worker."""

import gzip
import json
import threading
from email import message_from_bytes
from email.policy import HTTP
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

import orca
import orca_driver
import pytest

from printlog_orca import controller

FIXTURE = Path(__file__).parent / "fixtures" / "orcaslicer-2.2.0-rc-calibration-cube.gcode.gz"


@pytest.fixture
def api():
    received = []
    arrived = threading.Event()

    class Handler(BaseHTTPRequestHandler):
        def do_POST(self):  # noqa: N802 - http.server's name
            body = self.rfile.read(int(self.headers["Content-Length"]))
            received.append((self.path, self.headers["Content-Type"], body))
            answer = b'{"newSettingId":"11111111-2222-3333-4444-555555555555"}'
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(answer)))
            self.end_headers()
            self.wfile.write(answer)
            arrived.set()

        def log_message(self, *args):
            pass

    server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
    threading.Thread(target=server.serve_forever, args=(0.01,), daemon=True).start()
    yield f"http://127.0.0.1:{server.server_address[1]}", received, arrived
    server.shutdown()
    server.server_close()


def test_an_export_uploads_once_to_the_configured_api(api, tmp_path, monkeypatch):
    base, received, arrived = api
    storage = tmp_path / "OrcaSlicer" / "orca_plugins" / "plugin_data" / "3d-print-log"
    storage.mkdir(parents=True)
    orca_driver.reset(storage)
    monkeypatch.setattr(controller, "shared", controller.Controller())
    uploader = orca_driver.load()["3D Print Log uploader"]
    uploader.save_config(json.dumps({"api_base": base, "open_browser": False, "debug": True}))
    working = tmp_path / "plate_1.gcode.pp"
    working.write_bytes(gzip.decompress(FIXTURE.read_bytes()))

    ctx = orca.slicing.SlicingPipelineContext(
        gcode_path=str(working),
        host="File",
        output_name=str(tmp_path / "Calibration Cube_PLA_20m.gcode"),
        config={"print_settings_id": "0.20mm Standard @Voron", "printer_settings_id": "Voron"},
    )
    result = orca_driver.execute(uploader, ctx)

    assert result.status == orca.PluginResult.Success
    assert arrived.wait(30)
    ((path, content_type, body),) = received
    assert path == "/api/Slicer/uploads"
    message = message_from_bytes(
        f"Content-Type: {content_type}\r\n\r\n".encode() + body, policy=HTTP
    )
    parts = {p.get_param("name", header="content-disposition"): p for p in message.iter_parts()}
    metadata = json.loads(parts["metadata"].get_payload(decode=True))
    assert metadata["outputName"] == "Calibration Cube_PLA_20m.gcode"
    assert [m["name"] for m in metadata["models"]] == ["Calibration Cube.stl"]
    text = gzip.decompress(parts["gcode"].get_payload(decode=True)).decode("utf-8")
    assert "; generated by OrcaSlicer" in text

    debug = storage / "debug" / "last-upload.json"
    for _ in range(200):
        if debug.exists() and not list((storage / "uploads" / "jobs").iterdir()):
            break
        threading.Event().wait(0.05)
    assert json.loads(debug.read_text(encoding="utf-8"))["result"]["ok"] is True
    assert list((storage / "uploads" / "jobs").iterdir()) == []
    assert working.exists()
