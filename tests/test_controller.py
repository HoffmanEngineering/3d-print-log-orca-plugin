def test_the_upload_carries_the_install_id_and_names_from_the_send(env):
    ctl, api, storage, temp, _ = env
    sliced(ctl, temp, model="")
    ctl.mark_sent("PrintJobStarted", "Desk organizer")

    log(ctl, storage, items(ctl)[0]["id"])

