def test_a_declined_prompt_leaves_the_slice_loggable(env):
    ctl, api, storage, temp, _ = env
    api.error = PermissionError("declined")
    sliced(ctl, temp)
    slice_id = items(ctl)[0]["id"]

    event = log(ctl, storage, slice_id)

    assert event == {
        "kind": "failed",
        "id": slice_id,
        "message": uploader.DECLINED,
        "declined": True,
    }
    (item,) = items(ctl)
    assert item["status"] == "not logged"
    assert item["message"] == uploader.DECLINED
    assert item["error"] is True

    api.error = None
    assert log(ctl, storage, slice_id)["kind"] == "logged"


def test_an_api_error_shows_the_apis_message(env):
    ctl, api, storage, temp, _ = env
    api.result = UploadResult(False, 400, "HTTP 400, the API rejected the upload: bad template")
    sliced(ctl, temp)

    event = log(ctl, storage, items(ctl)[0]["id"])

    assert event["kind"] == "failed"
    assert "bad template" in event["message"]
    assert event["declined"] is False


