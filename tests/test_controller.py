"""The controller without Orca: what the slices list holds, and the log flow the tab drives."""

import json
import re

import pytest

from printlog_orca import controller, staging, uploader
from printlog_orca.client import UploadResult

SETTING_ID = "6f9619ff-8b86-d011-b42d-00c04fc964ff"


class FakeApi:
    def __init__(self):
        self.result = UploadResult(True, 200, "uploaded", SETTING_ID)
        self.error = None
        self.calls = []

    def __call__(self, api_base, body, content_type, timeout=30):
        self.calls.append(body)
        if self.error:
            raise self.error
        return self.result


class Clock:
    def __init__(self):
        self.now = 1_000_000.0

    def __call__(self):
        return self.now


@pytest.fixture
def env(tmp_path):
    storage = tmp_path / "OrcaSlicer" / "orca_plugins" / "plugin_data" / "printlog"
    storage.mkdir(parents=True)
    temp = tmp_path / "Temp"
    temp.mkdir()
    api = FakeApi()
    config = {}
    ctl = controller.Controller(clock=Clock(), upload=api)
    ctl.set_config_source(lambda: json.dumps(config))
    return ctl, api, storage, temp, config


def slice_file(temp, name=".1234.0.gcode", text="; generated by OrcaSlicer 2.5.0 on x\nG28\n"):
    path = temp / name
    path.write_text(text)
    return path


def sliced(ctl, temp, model="Benchy", name=".1234.0.gcode"):
    path = slice_file(temp, name)
    ctl.record_slice(str(path), model)
    return path


def items(ctl):
    return ctl.state()["slices"]


def log(ctl, storage, slice_id, relog=False):
    first = ctl.request_log(slice_id, relog=relog)
    if first["kind"] != "uploading":
        return first
    return ctl.finish_log(slice_id, storage)


# --- settings ---------------------------------------------------------------------------


def test_defaults():
    settings = controller.parse_settings("")

    assert settings == controller.Settings(
        template="default",
        open_claim_page="tab",
        api_base="https://api.3dprintlog.com",
        web_base="https://www.3dprintlog.com",
        slice_notification=True,
        debug=False,
    )


@pytest.mark.parametrize(
    ("key", "value"),
    [
        ("template", "fancy"),
        ("open_claim_page", "popup"),
        ("api_base", "ftp://x"),
        ("web_base", 3),
        ("slice_notification", "yes"),
        ("debug", 1),
    ],
)
def test_a_bad_value_falls_back_to_its_default(key, value):
    settings = controller.parse_settings(json.dumps({key: value}))

    assert getattr(settings, key) == getattr(controller.parse_settings(""), key)


def test_config_that_is_not_json_uses_the_defaults():
    assert controller.parse_settings("{oops") == controller.parse_settings("")


def test_trailing_slashes_are_dropped_and_old_keys_ignored():
    raw = json.dumps(
        {
            "api_base": "http://localhost:5000/",
            "open_browser": False,
            "bambu_send_window_minutes": 5,
        }
    )

    assert controller.parse_settings(raw).api_base == "http://localhost:5000"


def test_without_a_config_source_the_defaults_apply():
    assert controller.Controller().settings() == controller.parse_settings("")


# --- the slices list ----------------------------------------------------------------------


def test_a_slice_is_listed_as_not_sent_and_not_logged(env):
    ctl, _, _, temp, _ = env

    sliced(ctl, temp)

    (item,) = items(ctl)
    assert item["name"] == "Benchy"
    assert item["destination"] == "Not sent yet"
    assert item["status"] == "not logged"
    assert item["slicedAt"] == 1_000_000.0
    assert item["latest"] is True


def test_newest_slices_come_first_and_the_list_is_capped(env):
    ctl, _, _, temp, _ = env

    for n in range(controller.MAX_SLICES + 3):
        sliced(ctl, temp, model=f"Model {n}", name=f".1234.{n}.gcode")

    names = [item["name"] for item in items(ctl)]
    assert len(names) == controller.MAX_SLICES
    assert names[0] == f"Model {controller.MAX_SLICES + 2}"
    assert [item["latest"] for item in items(ctl)].count(True) == 1


def test_a_reslice_of_the_same_plate_replaces_its_pending_entry(env):
    ctl, _, _, temp, _ = env
    sliced(ctl, temp, model="Benchy")

    sliced(ctl, temp, model="Benchy v2")

    assert [item["name"] for item in items(ctl)] == ["Benchy v2"]


def test_a_reslice_keeps_a_logged_entry_but_it_cannot_be_logged_again(env):
    ctl, _, storage, temp, _ = env
    sliced(ctl, temp)
    first = items(ctl)[0]["id"]
    assert log(ctl, storage, first)["kind"] == "logged"

    sliced(ctl, temp, model="Benchy v2")

    old = next(item for item in items(ctl) if item["id"] == first)
    assert old["status"] == "logged"
    assert old["canLog"] is False


