# --- the optional hook ------------------------------------------------------------------------


def hook(ctl, storage, temp, host="File", output_name=None, name="plate.gcode.pp"):
    working = slice_file(temp, name, text="; generated by OrcaSlicer 2.5.0 on x\n; hooked\n")
    return ctl.on_gcode(
        storage_dir=storage,
        host=host,
        gcode_path=str(working),
        output_name=str(output_name if output_name is not None else temp / "Benchy_PLA.gcode"),
        orca_version="2.5.0-alpha",
        preset_ids={"print_settings_id": "0.20mm"},
    )


def test_the_hook_copies_an_export_and_marks_the_slice(env):
    ctl, api, storage, temp, _ = env
    sliced(ctl, temp)

    hook(ctl, storage, temp)

    (item,) = items(ctl)
    assert item["destination"] == "Exported to Benchy_PLA.gcode"
    assert len(list(staging.exports_dir(storage).iterdir())) == 1
    log(ctl, storage, item["id"])
    body = api.calls[0].decode("utf-8", errors="replace")
    assert '"outputName": "Benchy_PLA.gcode"' in body
    assert '"slicerVersion": "2.5.0-alpha"' in body


def test_the_hook_on_a_print_host_upload_names_the_host(env):
    ctl, _, storage, temp, _ = env
    sliced(ctl, temp)

    hook(ctl, storage, temp, host="OctoPrint", output_name="benchy.gcode")
    ctl.mark_sent("UploadStarted", ".OrcaSlicer.upload.1a2b")

    assert items(ctl)[0]["destination"] == "Sent to OctoPrint"


def test_the_bambu_after_slice_run_is_ignored(env):
    ctl, _, storage, temp, _ = env
    path = sliced(ctl, temp)

    message = ctl.on_gcode(
        storage_dir=storage,
        host="File",
        gcode_path=str(path),
        output_name=str(path),
        orca_version="2.5.0",
        preset_ids={},
    )

    assert message == ""
    assert not staging.exports_dir(storage).exists()


def test_a_newer_hook_copy_replaces_the_old_one(env):
    ctl, _, storage, temp, _ = env
    sliced(ctl, temp)
    hook(ctl, storage, temp)
    sliced(ctl, temp, name=".1234.1.gcode")

    hook(ctl, storage, temp)
    hook(ctl, storage, temp)

    assert len(list(staging.exports_dir(storage).iterdir())) == 2  # one per listed slice
