# --- logging ------------------------------------------------------------------------------


def test_log_marks_uploading_then_uploads_once_and_returns_the_claim_url(env):
    ctl, api, storage, temp, _ = env
    sliced(ctl, temp)
    slice_id = items(ctl)[0]["id"]

    first = ctl.request_log(slice_id)

    assert first == {"kind": "uploading", "id": slice_id}
    assert items(ctl)[0]["status"] == "uploading"
    assert api.calls == []

    done = ctl.finish_log(slice_id, storage)

    assert done["kind"] == "logged"
    assert done["url"].endswith(f"settingId={SETTING_ID}")
    assert done["mode"] == "tab"
    assert len(api.calls) == 1
    (item,) = items(ctl)
    assert item["status"] == "logged"
    assert item["claimUrl"] == done["url"]


def test_logging_a_logged_slice_asks_first(env):
    ctl, api, storage, temp, _ = env
    sliced(ctl, temp)
    slice_id = items(ctl)[0]["id"]
    log(ctl, storage, slice_id)

    again = ctl.request_log(slice_id)

    assert again["kind"] == "already_logged"
    assert again["url"].endswith(SETTING_ID)
    assert len(api.calls) == 1

    assert log(ctl, storage, slice_id, relog=True)["kind"] == "logged"
    assert len(api.calls) == 2


def test_upload_without_a_log_request_does_nothing(env):
    ctl, api, storage, temp, _ = env
    sliced(ctl, temp)

    event = ctl.finish_log(items(ctl)[0]["id"], storage)

    assert event["kind"] == "missing"
    assert api.calls == []


