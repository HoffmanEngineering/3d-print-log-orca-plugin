"""Ported from GcodeWindowTests: the plugin sends what GcodeWindow.ReadFromFile would read."""

from printlog_orca import gcode_window
from printlog_orca.gcode_window import WINDOW_SIZE


def write(tmp_path, data):
    path = tmp_path / "print.gcode"
    path.write_bytes(data)
    return path


def test_window_size_matches_the_parser():
    assert WINDOW_SIZE == 2_000_000


def test_reads_the_whole_file_when_it_is_small(tmp_path):
    path = write(tmp_path, b"; generated by OrcaSlicer\n; layer_height = 0.2\n")

    assert gcode_window.read(path) == "; generated by OrcaSlicer\n; layer_height = 0.2\n"


def test_strips_the_byte_order_mark(tmp_path):
    path = write(tmp_path, b"\xef\xbb\xbf; generated by OrcaSlicer\n")

    assert gcode_window.read(path) == "; generated by OrcaSlicer\n"


def test_reads_the_whole_file_at_exactly_two_windows(tmp_path):
    data = b"H" * WINDOW_SIZE + b"T" * WINDOW_SIZE
    path = write(tmp_path, data)

    assert gcode_window.read(path) == data.decode()


def test_keeps_head_and_tail_joined_by_a_newline_when_large(tmp_path):
    head = b"H" * WINDOW_SIZE
    tail = b"T" * WINDOW_SIZE
    path = write(tmp_path, head + b"MIDDLE" + tail)

    assert gcode_window.read(path) == head.decode() + "\n" + tail.decode()


def test_strips_the_byte_order_mark_from_a_large_file(tmp_path):
    path = write(tmp_path, b"\xef\xbb\xbf; HEAD\n" + b"G" * (WINDOW_SIZE * 3) + b"\n; TAIL\n")

    result = gcode_window.read(path)

    assert result.startswith("; HEAD\n")
    assert result.endswith("\n; TAIL\n")
    assert len(result) <= WINDOW_SIZE * 2 + 1


def test_does_not_fail_when_the_tail_starts_inside_a_multibyte_character(tmp_path):
    euro = "€".encode()
    path = write(tmp_path, b"; HEAD\n" + euro * WINDOW_SIZE + b"\n; TAIL\n")

    result = gcode_window.read(path)

    assert result.endswith("\n; TAIL\n")


def test_invalid_utf8_in_a_small_file_becomes_replacement_characters(tmp_path):
    path = write(tmp_path, b"; name = caf\xe9\n")

    assert gcode_window.read(path) == "; name = caf�\n"
