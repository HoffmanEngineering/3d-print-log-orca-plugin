"""The request body the API's POST /api/Slicer/uploads takes (spec: API payload contract)."""

import gzip
import json
from email import message_from_bytes
from email.policy import HTTP

import pytest

from printlog_orca import payload
from printlog_orca.object_bounds import ObjectBounds
from printlog_orca.presets import UserPreset


def parts(body, content_type):
    message = message_from_bytes(
        f"Content-Type: {content_type}\r\n\r\n".encode() + body, policy=HTTP
    )
    assert message.is_multipart()
    return {
        part.get_param("name", header="content-disposition"): part for part in message.iter_parts()
    }


def make_metadata(**overrides):
    fields = {
        "plugin_version": "0.1.0",
        "slicer_version": "2.5.0-alpha",
        "output_name": "3DBenchy_PLA_1h2m.gcode",
        "host": "File",
        "template": "default",
        "bounds": [],
        "user_presets": [],
    }
    fields.update(overrides)
    return payload.metadata(**fields)


def test_metadata_has_the_contract_fields():
    bounds = ObjectBounds("3DBenchy.stl", 100.1, 159.6, 95.2, 125.7, 48.0, has_points=True)
    preset = UserPreset("process", "0.20mm Mine", '{"wall_loops":"3"}')

    metadata = make_metadata(bounds=[bounds], user_presets=[preset])

    assert metadata == {
        "pluginVersion": "0.1.0",
        "slicerVersion": "2.5.0-alpha",
        "outputName": "3DBenchy_PLA_1h2m.gcode",
        "host": "File",
        "template": "default",
        "models": [
            {
                "name": "3DBenchy.stl",
                "minX": 100.1,
                "maxX": 159.6,
                "minY": 95.2,
                "maxY": 125.7,
                "maxZ": 48.0,
            }
        ],
        "userPresets": [{"kind": "process", "name": "0.20mm Mine", "json": '{"wall_loops":"3"}'}],
    }


@pytest.mark.parametrize(
    ("output_name", "expected"),
    [
        ("C:\\Users\\chris\\Desktop\\benchy.gcode", "benchy.gcode"),
        ("/home/chris/prints/benchy.gcode", "benchy.gcode"),
        ("subfolder/benchy.gcode", "benchy.gcode"),
        ("benchy.gcode", "benchy.gcode"),
    ],
)
def test_output_name_is_only_the_file_name(output_name, expected):
    # The path holds the user's account name, and the server's Path.GetFileName (on Linux)
    # would not split at a backslash.
    assert make_metadata(output_name=output_name)["outputName"] == expected


def test_encode_sends_the_text_gzipped_and_the_metadata_as_json():
    text = "; generated by OrcaSlicer 2.5.0\n; Würfel\n"
    metadata = make_metadata()

    body, content_type = payload.encode(text, metadata)
    sent = parts(body, content_type)

    assert content_type.startswith("multipart/form-data; boundary=")
    assert set(sent) == {"gcode", "metadata"}
    assert sent["gcode"].get_filename()
    assert gzip.decompress(sent["gcode"].get_payload(decode=True)).decode("utf-8") == text
    assert json.loads(sent["metadata"].get_payload(decode=True).decode("utf-8")) == metadata


def test_the_boundary_never_appears_in_the_content():
    body, content_type = payload.encode("x" * 10_000, make_metadata())
    boundary = content_type.split("boundary=")[1].encode()

    assert body.count(boundary) == 3  # two part delimiters and the closing one
